import { useEffect, useState } from 'react';
import { AlertCircle, Lightbulb, ShieldAlert, Sparkles } from 'lucide-react';
import type { Comparison } from '@/lib/unfollowly/compare';
import { getInsightsStatus, requestInsights, type Insights } from '@/lib/unfollowly/insights';

interface Props { results: Comparison | null }

export function InsightsCard({ results }: Props) {
  const [configured, setConfigured] = useState<boolean | null>(null);
  const [insights, setInsights] = useState<Insights | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  useEffect(() => { void getInsightsStatus().then(setConfigured); }, []);

  // New comparison means old insights no longer apply.
  useEffect(() => { setInsights(null); setError(''); }, [results]);

  const hasChanges = Boolean(results && (results.lost.length || results.gained.length));

  async function analyze() {
    if (!results) return;
    setLoading(true); setError('');
    try {
      setInsights(await requestInsights(results));
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Could not generate insights.');
    } finally {
      setLoading(false);
    }
  }

  return (
    <section className="insights" aria-labelledby="insights-heading">
      <div className="section-heading">
        <div><span className="eyebrow">AI INSIGHTS · MUSE SPARK</span><h2 id="insights-heading">What changed, explained</h2></div>
        {configured && hasChanges && (
          <button type="button" className="primary" onClick={() => void analyze()} disabled={loading}>
            <Sparkles size={17} aria-hidden="true" /> {loading ? 'Analyzing…' : insights ? 'Analyze again' : 'Analyze with Muse Spark'}
          </button>
        )}
      </div>

      <div className="insights-card" aria-busy={loading} aria-live="polite">
        {configured === false ? (
          <p className="muted">AI insights aren't set up on this server. Add a Meta Model API key (<code>MODEL_API_KEY</code>) to <code>.env</code> to enable them.</p>
        ) : !results ? (
          <p className="muted">Compare two snapshots (or try the demo) and Muse Spark will explain the changes: patterns in who left and who joined, likely spam accounts, and tips.</p>
        ) : !hasChanges ? (
          <p className="muted">No follower changes to analyze.</p>
        ) : loading ? (
          <p className="muted">Muse Spark is reading {results.lost.length + results.gained.length} changed accounts…</p>
        ) : insights ? (
          <div className="insights-body">
            {insights.summary && <p className="insights-summary">{insights.summary}</p>}
            {insights.patterns.length > 0 && (
              <ul className="insights-patterns">
                {insights.patterns.map((p) => <li key={p.title}><strong>{p.title}</strong><span>{p.detail}</span></li>)}
              </ul>
            )}
            {insights.possibleSpam.length > 0 && (
              <div className="insights-block">
                <h3><ShieldAlert size={15} aria-hidden="true" /> Possible spam or bot accounts</h3>
                <p>{insights.possibleSpam.map((n) => `@${n}`).join(', ')}</p>
              </div>
            )}
            {insights.suggestions.length > 0 && (
              <div className="insights-block">
                <h3><Lightbulb size={15} aria-hidden="true" /> Suggestions</h3>
                <ul>{insights.suggestions.map((s) => <li key={s}>{s}</li>)}</ul>
              </div>
            )}
            <p className="insights-note">Generated by Muse Spark from usernames only. Treat these as educated guesses.</p>
          </div>
        ) : (
          <p className="muted">Only the {results.lost.length + results.gained.length} changed usernames are sent to Meta's Muse Spark model when you click Analyze. Your full follower list stays in this browser.</p>
        )}
      </div>

      {error && <div className="error" role="alert"><AlertCircle size={17} aria-hidden="true" /><span>{error}</span></div>}
    </section>
  );
}
